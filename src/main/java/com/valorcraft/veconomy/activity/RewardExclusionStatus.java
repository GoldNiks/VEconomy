package com.valorcraft.veconomy.activity;

/**
 * Результат чтения флага исключения из наград.
 * <p>
 * Три состояния обязательны для fail-closed поведения: {@link #UNKNOWN} означает,
 * что проверить флаг не удалось (ошибка базы), и награду выдавать нельзя —
 * интерпретация ошибки как {@code false} разблокировала бы выплаты исключённым.
 */
public enum RewardExclusionStatus {

    /** Флаг установлен: игрок исключён из наград. */
    EXCLUDED,
    /** Флаг снят (или записи ещё нет): игрок не исключён. */
    NOT_EXCLUDED,
    /** Статус прочитать не удалось (ошибка базы): награда должна быть удержана. */
    UNKNOWN
}
