package com.valorcraft.veconomy.audit;

/** Уровень важности аудит-события. */
public enum AuditSeverity {
    /** Штатные административные действия и автоматические начисления. */
    INFO,
    /** Заметный, но пока не подозрительный факт. */
    WARNING,
    /** Сработавший сигнал подозрительной активности (эвристика). */
    SUSPICIOUS,
    /** Требует внимания администратора. */
    CRITICAL
}