package com.valorcraft.veconomy.api;

/** Статус личного аккаунта игрока (и системной казны). */
public enum AccountStatus {
    /** Аккаунт активен, операции разрешены. */
    ACTIVE,
    /** Аккаунт заморожен администрацией; операции запрещены. */
    FROZEN,
    /** Системный аккаунт (например, казна). */
    SYSTEM
}
