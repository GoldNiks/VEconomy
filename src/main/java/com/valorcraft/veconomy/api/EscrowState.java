package com.valorcraft.veconomy.api;

/** Состояние эскроу-записи. */
public enum EscrowState {
    /** Средства зарезервированы у владельца и удерживаются системой. */
    RESERVED,
    /** Средства переданы получателю (операция завершена). */
    CAPTURED,
    /** Средства возвращены владельцу (операция отменена). */
    RELEASED
}
